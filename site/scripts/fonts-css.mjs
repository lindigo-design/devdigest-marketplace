#!/usr/bin/env node
// Generates src/styles/fonts.css from the @fontsource packages: only the faces, weights and subsets the
// design tokens use, under the family names tokens.css expects. Fonts are bundled at build time, so the
// site makes no third-party font requests (spec CAT-01 R7/AC-5).
//
//   node scripts/fonts-css.mjs          write src/styles/fonts.css
//   node scripts/fonts-css.mjs --check  exit 1 if the file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SITE = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(SITE, "src/styles/fonts.css");
const require = createRequire(join(SITE, "package.json"));

// Latin for UI text, Cyrillic for Ukrainian queries and content (design-tokens.md §1).
export const SUBSETS = ["latin", "latin-ext", "cyrillic", "cyrillic-ext"];

// family: the name tokens.css uses; pkg + css: the fontsource stylesheet that holds every subset with its unicode-range.
export const FACES = [
  { family: "Source Serif 4", pkg: "@fontsource-variable/source-serif-4", css: ["opsz.css"] },
  { family: "IBM Plex Sans", pkg: "@fontsource/ibm-plex-sans", css: ["400.css", "500.css", "600.css"] },
  { family: "IBM Plex Mono", pkg: "@fontsource/ibm-plex-mono", css: ["400.css", "500.css"] },
];

const BLOCK = /\/\* ([\w-]+) \*\/\s*@font-face\s*\{([^}]*)\}/g;

function faces({ family, pkg, css }) {
  const root = dirname(require.resolve(`${pkg}/package.json`));
  const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;
  const out = [];
  for (const file of css) {
    const text = readFileSync(join(root, file), "utf8");
    for (const [, id, body] of text.matchAll(BLOCK)) {
      const subset = SUBSETS.find((s) => new RegExp(`-${s}-(?:\\d+|opsz)-normal$`).test(id));
      if (!subset || !/font-style:\s*normal/.test(body)) continue;
      const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)?.[1];
      const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1].trim();
      const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1].trim();
      if (!woff2 || !weight || !range) throw new Error(`${pkg}/${file}: cannot parse @font-face "${id}"`);
      const format = /variations/.test(body) ? "woff2-variations" : "woff2";
      out.push(
        `/* ${id} (${pkg}@${version}) */\n@font-face {\n  font-family: "${family}";\n  font-style: normal;\n` +
          `  font-display: swap;\n  font-weight: ${weight};\n  src: url("${pkg}/files/${woff2}") format("${format}");\n` +
          `  unicode-range: ${range};\n}`,
      );
    }
  }
  if (out.length !== css.length * SUBSETS.length) {
    throw new Error(`${pkg}: expected ${css.length * SUBSETS.length} faces, found ${out.length}`);
  }
  return out;
}

export function render() {
  const header =
    "/*\n * Self-hosted fonts (OFL), bundled at build time. GENERATED by scripts/fonts-css.mjs from the @fontsource\n" +
    " * packages in package.json: do not edit by hand. Subsets: " + SUBSETS.join(", ") + ".\n */\n";
  return `${header}\n${FACES.flatMap(faces).join("\n\n")}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const css = render();
  if (process.argv.includes("--check")) {
    const current = (() => { try { return readFileSync(OUT, "utf8").replace(/\r\n/g, "\n"); } catch { return ""; } })();
    if (current !== css) {
      console.error("src/styles/fonts.css is out of date; run: node scripts/fonts-css.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, css);
    console.log(`wrote ${OUT}`);
  }
}
